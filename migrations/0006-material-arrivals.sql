-- Existing receipt facts keep a NULL arrival; historical delivery rounds cannot be inferred.
CREATE TABLE IF NOT EXISTS material_arrivals(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES material_requests(id), request_revision BIGINT NOT NULL CHECK(request_revision>0),
  actor_id BIGINT NOT NULL REFERENCES users(id), created_at TEXT NOT NULL,
  document_version BIGINT NOT NULL DEFAULT 0 CHECK(document_version>=0)
);
CREATE TABLE IF NOT EXISTS material_arrival_document_versions(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  arrival_id BIGINT NOT NULL REFERENCES material_arrivals(id), version BIGINT NOT NULL CHECK(version>0),
  reason TEXT NOT NULL DEFAULT '', actor_id BIGINT NOT NULL REFERENCES users(id), created_at TEXT NOT NULL,
  UNIQUE(arrival_id,version)
);
ALTER TABLE material_receipts ADD COLUMN IF NOT EXISTS arrival_id BIGINT REFERENCES material_arrivals(id);
ALTER TABLE material_receipts ADD COLUMN IF NOT EXISTS expected_manufacturer TEXT NOT NULL DEFAULT '';
ALTER TABLE material_receipts ADD COLUMN IF NOT EXISTS manufacturer_status TEXT NOT NULL DEFAULT 'legacy' CHECK(manufacturer_status IN ('legacy','known','unknown'));
ALTER TABLE material_receipts ADD COLUMN IF NOT EXISTS manufacturer_reason TEXT NOT NULL DEFAULT '';
ALTER TABLE material_receipts ADD COLUMN IF NOT EXISTS difference_reason TEXT NOT NULL DEFAULT '';
ALTER TABLE material_attachments ADD COLUMN IF NOT EXISTS document_version_id BIGINT REFERENCES material_arrival_document_versions(id);
ALTER TABLE material_attachments ADD COLUMN IF NOT EXISTS sha256 TEXT NOT NULL DEFAULT '' CHECK(sha256='' OR sha256 ~ '^[a-f0-9]{64}$');
ALTER TABLE material_attachments DROP CONSTRAINT IF EXISTS material_attachments_check;
ALTER TABLE material_attachments ADD CONSTRAINT material_attachments_check CHECK(
  (request_id IS NOT NULL)::integer+(receipt_id IS NOT NULL)::integer+(document_version_id IS NOT NULL)::integer=1
);
CREATE INDEX IF NOT EXISTS material_arrival_request ON material_arrivals(request_id,id);
CREATE INDEX IF NOT EXISTS material_receipt_arrival ON material_receipts(arrival_id,id);
CREATE INDEX IF NOT EXISTS material_attachment_document ON material_attachments(document_version_id,id);
