CREATE TABLE IF NOT EXISTS material_storage_places(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK(length(name)>0 AND length(name)<=60),
  parent_id BIGINT REFERENCES material_storage_places(id) DEFERRABLE INITIALLY DEFERRED,
  active BIGINT NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
  version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
  created_by BIGINT NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
  CHECK(parent_id IS NULL OR parent_id<>id)
);
CREATE UNIQUE INDEX IF NOT EXISTS material_place_siblings ON material_storage_places(COALESCE(parent_id,0),lower(name));
